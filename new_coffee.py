def mixup_batch(x, y, w, alpha):
    x = tf.cast(x, tf.float32); y = tf.cast(y, tf.float32); w = tf.cast(w, tf.float32)
    b = tf.shape(x)[0]
    g1 = tf.random.gamma([], alpha, dtype=tf.float32); g2 = tf.random.gamma([], alpha, dtype=tf.float32)
    lam = g1 / (g1 + g2 + 1e-8)
    idx = tf.random.shuffle(tf.range(b))
    return (lam * x + (1 - lam) * tf.gather(x, idx),
            lam * y + (1 - lam) * tf.gather(y, idx),
            lam * w + (1 - lam) * tf.gather(w, idx))

def make_ds(idx, size, train=False, sample_weight=None, mixup_alpha=0.0):
    y = to_categorical(labels[idx], NUM_CLASSES).astype("float32")
    tensors = (filepaths[idx], y) if sample_weight is None else (filepaths[idx], y, sample_weight.astype("float32"))
    ds = tf.data.Dataset.from_tensor_slices(tensors)
    if train:
        ds = ds.shuffle(len(idx), reshuffle_each_iteration=True)

    def load(path, *rest):
        img = tf.io.read_file(path)
        img = tf.image.decode_image(img, channels=3, expand_animations=False)
        img.set_shape([None, None, 3])
        img = tf.image.resize(img, (size, size))
        return (tf.cast(img, tf.float32), *rest)

    ds = ds.map(load, num_parallel_calls=tf.data.AUTOTUNE).batch(BATCH_SIZE)
    if train and mixup_alpha > 0 and sample_weight is not None:
        ds = ds.map(lambda x, y, w: mixup_batch(x, y, w, mixup_alpha), num_parallel_calls=tf.data.AUTOTUNE)
    return ds.prefetch(tf.data.AUTOTUNE)

def sample_epoch_indices(train_idx, per_group):
    g = groups[train_idx]
    order = np.argsort(g, kind="stable")
    g_sorted = g[order]
    bounds = np.flatnonzero(np.r_[True, g_sorted[1:] != g_sorted[:-1], True])
    chosen = []
    for a, b in zip(bounds[:-1], bounds[1:]):
        members = train_idx[order[a:b]]
        chosen.append(rng.choice(members, size=min(per_group, len(members)), replace=False))
    return np.concatenate(chosen)

