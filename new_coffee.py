def train_and_evaluate(variant, fold, tr, va, te):
    cfg = dict(variant=variant, DROPOUT=DROPOUT, LABEL_SMOOTH=LABEL_SMOOTH, SPG=SAMPLES_PER_GROUP, SIZE=SIZE)
    rhash = hashlib.md5(json.dumps(cfg, sort_keys=True).encode()).hexdigest()[:6]
    res_path = f"{OUTPUT_DIR}/DNN-{variant}_{rhash}_fold{fold}_result.json"
    pred_path = f"{OUTPUT_DIR}/DNN-{variant}_fold{fold}_test_pred.npy"
    if os.path.exists(res_path) and os.path.exists(pred_path):
        print(f"\n[DNN-{variant}] finished run found, loading it (delete {res_path} to retrain).")
        return json.load(open(res_path)), np.load(pred_path)
    print(f"\n{'='*60}\nFold {fold} - DNN [{variant}] @ {SIZE}px\n{'='*60}")
    t0 = time.time()
    model, hist, info = train_model(variant, tr, va)
    y_pred = model.predict(make_ds(te, SIZE), verbose=0).argmax(1)      # test touched here only
    y_true = labels[te]
