def mcnemar_test(y_true, p1, p2, n1, n2):
    c1, c2 = (p1 == y_true), (p2 == y_true)
    b = int(np.sum(c1 & ~c2)); c = int(np.sum(~c1 & c2))
    if b + c == 0:
        return f"McNemar ({n1} vs {n2}): no discordant pairs"
    if b + c < 25:
        p, kind = binomtest(min(b, c), b + c, 0.5).pvalue, "exact"
    else:
        p, kind = 1 - chi2.cdf((abs(b - c) - 1) ** 2 / (b + c), 1), "chi2 (continuity-corrected)"
    return f"McNemar ({n1} vs {n2}): b={b}, c={c}, p={p:.4g} [{kind}]"
# Images in one group are highly correlated, so these p-values are optimistic. Report with that caveat.

def group_mean_accuracy(te, y_pred):
    df = pd.DataFrame({"g": groups[te], "ok": (y_pred == labels[te]).astype(float)})
    return df.groupby("g")["ok"].mean().mean()

