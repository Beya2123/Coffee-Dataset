class UnionFind:
    def __init__(self, n): self.p = list(range(n))
    def find(self, x):
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x
    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb: self.p[rb] = ra

def orientation_hashes(path):
    img = Image.open(path).convert("L")
    img.draft("L", (128, 128))
    arr = np.array(img.resize((64, 64)))
    out = []
    for flip in (False, True):
        base = np.fliplr(arr) if flip else arr
        for k in range(4):
            h = imagehash.phash(Image.fromarray(np.rot90(base, k).copy()))
            out.append(int(str(h), 16))
    return out

