def make_ds(idx, size, train=False, sample_weight=None):
    y = to_categorical(labels[idx], NUM_CLASSES)
    tensors = (filepaths[idx], y) if sample_weight is None else (filepaths[idx], y, sample_weight.astype("float32"))
    ds = tf.data.Dataset.from_tensor_slices(tensors)
    if train:
        ds = ds.shuffle(len(idx), reshuffle_each_iteration=True)

    def load(path, *rest):
        img = tf.io.read_file(path)
        img = tf.image.decode_image(img, channels=3, expand_animations=False)
        img.set_shape([None, None, 3])
        img = tf.image.resize(img, (size, size))
        return (tf.cast(img, tf.float32), *rest)

    ds = ds.map(load, num_parallel_calls=tf.data.AUTOTUNE)
    return ds.batch(BATCH_SIZE).prefetch(tf.data.AUTOTUNE)

def sample_epoch_indices(train_idx):
    """Draw at most SAMPLES_PER_GROUP images from every training group."""
    g = groups[train_idx]
    order = np.argsort(g, kind="stable")
    g_sorted = g[order]
    bounds = np.flatnonzero(np.r_[True, g_sorted[1:] != g_sorted[:-1], True])
    chosen = []
    for a, b in zip(bounds[:-1], bounds[1:]):
        members = train_idx[order[a:b]]
        k = min(SAMPLES_PER_GROUP, len(members))
        chosen.append(rng.choice(members, size=k, replace=False))
    return np.concatenate(chosen)

