def train_model(variant, tr, va):
    model = builders[variant](SIZE)
    val_ds = make_ds(va, SIZE)
    y_val = labels[va]
    hist = {"loss": [], "accuracy": [], "val_loss": [], "val_accuracy": [], "val_f1": []}
    best_f1, best_loss, best_w, wait = -1.0, np.inf, None, 0

    for epoch in range(EPOCHS):
        ep_idx = sample_epoch_indices(tr, SAMPLES_PER_GROUP)
        cw = compute_class_weight("balanced", classes=np.arange(NUM_CLASSES), y=labels[ep_idx])
        ds = make_ds(ep_idx, SIZE, train=True, sample_weight=cw[labels[ep_idx]])
        h = model.fit(ds, epochs=1, verbose=0)

        probs = model.predict(val_ds, verbose=0)
        pred = probs.argmax(1)
        v_loss = safe_log_loss(y_val, probs)
        v_acc = accuracy_score(y_val, pred)
        v_f1 = f1_score(y_val, pred, average="macro")
        hist["loss"].append(h.history["loss"][0]); hist["accuracy"].append(h.history["accuracy"][0])
        hist["val_loss"].append(v_loss); hist["val_accuracy"].append(v_acc); hist["val_f1"].append(v_f1)

        lr = get_lr(model)
        print(f"[DNN-{variant}] ep {epoch+1:02d}/{EPOCHS} n={len(ep_idx)} "
              f"train_acc={hist['accuracy'][-1]:.4f} loss={hist['loss'][-1]:.4f} | "
              f"val_acc={v_acc:.4f} val_f1={v_f1:.4f} val_loss={v_loss:.4f} | lr={lr:.2e}")

        improved = (v_f1 > best_f1 + 1e-4) or (abs(v_f1 - best_f1) <= 1e-4 and v_loss < best_loss - 1e-4)
        if improved:
            best_f1, best_loss, best_w, wait = max(v_f1, best_f1), v_loss, model.get_weights(), 0
        else:
            wait += 1
            if wait % LR_PATIENCE == 0:
                set_lr(model, max(lr * 0.3, 1e-7))
            if wait >= PATIENCE:
                print(f"[DNN-{variant}] early stopping (best val macro-F1 = {best_f1:.4f})")
                break
    model.set_weights(best_w)
    return model, hist, {"val_f1": float(best_f1), "val_loss": float(best_loss), "epochs": len(hist["loss"])}

