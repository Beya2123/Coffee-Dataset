def count_params(model):
    if model == "FF-CNN":
        inp = layers.Input(shape=(SIZE, SIZE, 3)); x = inp
        for f, k in [(32, 5), (64, 5), (128, 3), (256, 3), (512, 3)]:
            x = layers.Conv2D(f, k, padding="same")(x); x = layers.BatchNormalization()(x)
            x = layers.Activation("relu")(x); x = layers.MaxPooling2D(2)(x)
        x = layers.GlobalAveragePooling2D()(x); x = layers.Dense(256, activation="relu")(x)
