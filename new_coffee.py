def train_and_evaluate(name, recipe_name, fold, tr, va, te):
    size = SIZES[name]
    # resume support: a finished run is reloaded unless its recipe settings changed
    rhash = hashlib.md5(json.dumps(RECIPES[recipe_name], sort_keys=True, default=str).encode()).hexdigest()[:6]
    res_path = f"{OUTPUT_DIR}/{name}_{recipe_name}_{rhash}_fold{fold}_result.json"
    pred_path = f"{OUTPUT_DIR}/{name}_{recipe_name}_{rhash}_fold{fold}_pred.npy"
    if os.path.exists(res_path) and os.path.exists(pred_path):
        print(f"\n[{name}/{recipe_name}] finished run found, loading it (delete {res_path} to retrain).")
        return json.load(open(res_path)), np.load(pred_path)
    print(f"\n{'='*60}\nFold {fold} - {name} [{recipe_name} recipe] @ {size}px\n{'='*60}")
    t0 = time.time()
    model, hist, info = train_model(name, tr, va, size, recipe_name)
    y_pred = model.predict(make_ds(te, size), verbose=0).argmax(1)       # test touched here only
    y_true = labels[te]
    res = dict(model=name, recipe=recipe_name, fold=fold, **info,
               test_acc=float(accuracy_score(y_true, y_pred)),
               test_macro_f1=float(f1_score(y_true, y_pred, average="macro")),
               test_group_acc=float(group_mean_accuracy(te, y_pred)),
               minutes=(time.time() - t0) / 60)
    np.save(f"{OUTPUT_DIR}/{name}_{recipe_name}_fold{fold}_test_pred.npy", y_pred)
    np.save(pred_path, y_pred)
    with open(res_path, "w") as f:
        json.dump(res, f)
    save_artifacts(f"{name}_{recipe_name}", fold, y_true, y_pred, hist)
    print(f">>> {name}/{recipe_name}: VAL f1={info['val_f1']*100:.2f}% | "
          f"TEST acc={res['test_acc']*100:.2f}%  macro-F1={res['test_macro_f1']*100:.2f}%  "
          f"group-acc={res['test_group_acc']*100:.2f}%  ({res['minutes']:.1f} min)")
    del model; tf.keras.backend.clear_session(); gc.collect()
    return res, y_pred

