# 6. TRAINING LOOP (per-group sampling, class weights, early stopping on val macro-F1)
# ------------------------------------------------------------
def train_model(name, tr, va, size):
    model = model_builders[name](size)
    val_ds = make_ds(va, size)
    y_val = labels[va]
    hist = {"loss": [], "accuracy": [], "val_loss": [], "val_accuracy": [], "val_f1": []}
    best, best_w, wait = -1.0, None, 0

    for epoch in range(EPOCHS):
        ep_idx = sample_epoch_indices(tr)
        cw = compute_class_weight("balanced", classes=np.arange(NUM_CLASSES), y=labels[ep_idx])
        sw = cw[labels[ep_idx]]
        ds = make_ds(ep_idx, size, train=True, sample_weight=sw)
        h = model.fit(ds, epochs=1, verbose=0)

        probs = model.predict(val_ds, verbose=0)
        pred = probs.argmax(1)
        v_loss = log_loss(y_val, probs, labels=np.arange(NUM_CLASSES))
        v_acc = accuracy_score(y_val, pred)
        v_f1 = f1_score(y_val, pred, average="macro")
        hist["loss"].append(h.history["loss"][0]); hist["accuracy"].append(h.history["accuracy"][0])
        hist["val_loss"].append(v_loss); hist["val_accuracy"].append(v_acc); hist["val_f1"].append(v_f1)

        lr = float(model.optimizer.learning_rate.numpy()) if hasattr(model.optimizer.learning_rate, "numpy") \
            else float(model.optimizer.learning_rate)
        print(f"[{name}] ep {epoch+1:02d}/{EPOCHS} n={len(ep_idx)} "
              f"train_acc={hist['accuracy'][-1]:.4f} loss={hist['loss'][-1]:.4f} | "
              f"val_acc={v_acc:.4f} val_f1={v_f1:.4f} val_loss={v_loss:.4f} | lr={lr:.2e}")

        if v_f1 > best + 1e-4:
            best, best_w, wait = v_f1, model.get_weights(), 0
        else:
            wait += 1
            if wait % LR_PATIENCE == 0:
                model.optimizer.learning_rate.assign(max(lr * 0.3, 1e-7))
            if wait >= PATIENCE:
                print(f"[{name}] early stopping (best val macro-F1 = {best:.4f})")
                break
    model.set_weights(best_w)
    return model, hist

def group_mean_accuracy(te, y_pred):
    df = pd.DataFrame({"g": groups[te], "ok": (y_pred == labels[te]).astype(float)})
    return df.groupby("g")["ok"].mean().mean()

