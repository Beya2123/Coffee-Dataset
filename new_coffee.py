class RandomCutout(layers.Layer):
    def __init__(self, frac=0.25, prob=0.5, **kw):
        super().__init__(**kw); self.frac, self.prob = frac, prob
    def call(self, x, training=None):
        if not training: return x
        b = tf.shape(x)[0]; h = tf.shape(x)[1]; w = tf.shape(x)[2]
        half = tf.cast(tf.cast(h, tf.float32) * self.frac / 2, tf.int32)
        cy = tf.random.uniform([b], 0, h, tf.int32)
        cx = tf.random.uniform([b], 0, w, tf.int32)
        ys = tf.range(h)[None, :, None]; xs = tf.range(w)[None, None, :]
        mask = (tf.abs(ys - cy[:, None, None]) < half) & (tf.abs(xs - cx[:, None, None]) < half)
        keep = tf.random.uniform([b]) < self.prob
        mask = (mask & keep[:, None, None])[..., None]
        return tf.where(mask, tf.constant(127.5, x.dtype), x)

def augment(R):
    return Sequential([
        layers.RandomFlip("horizontal_and_vertical"),
        layers.RandomRotation(R["rot"]),
        layers.RandomZoom(R["zoom"]),
        layers.RandomTranslation(0.1, 0.1),
        layers.RandomContrast(0.25),
        layers.RandomBrightness(0.2, value_range=(0, 255)),
        RandomCutout(*R["cutout"]),
    ], name="augment")

def compile_model(m, R, lr):
    opt = AdamW(lr, weight_decay=R["weight_decay"]) if R["weight_decay"] > 0 else Adam(lr)
    m.compile(optimizer=opt, loss=CategoricalCrossentropy(label_smoothing=R["label_smooth"]),
              metrics=["accuracy"])
    return m

def unfreeze_top(base, fraction):
    base.trainable = True
    n_freeze = int(len(base.layers) * (1 - fraction))
    for i, l in enumerate(base.layers):
        l.trainable = (i >= n_freeze) and not isinstance(l, layers.BatchNormalization)

def classifier_head(x, R):
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(R["dropout"])(x)
    return layers.Dense(NUM_CLASSES, activation="softmax", dtype="float32")(x)

def build_resnet(size, R):
    inp = layers.Input(shape=(size, size, 3))
    x = augment(R)(inp)
    x = layers.Lambda(resnet_preprocess, name="resnet_preprocess")(x)
    base = ResNet50(weights="imagenet", include_top=False, input_shape=(size, size, 3))
    unfreeze_top(base, R["ft_frac"]["ResNet50"])
    x = base(x, training=False)
    return compile_model(Model(inp, classifier_head(x, R), name="ResNet50"), R, R["lr"]["ResNet50"])

def build_inception(size, R):
    inp = layers.Input(shape=(size, size, 3))
    x = augment(R)(inp)
    x = layers.Rescaling(1 / 127.5, offset=-1)(x)
    base = InceptionV3(weights="imagenet", include_top=False, input_shape=(size, size, 3))
    unfreeze_top(base, R["ft_frac"]["InceptionV3"])
    x = base(x, training=False)
    return compile_model(Model(inp, classifier_head(x, R), name="InceptionV3"), R, R["lr"]["InceptionV3"])

def build_dnn(size, R):
    inp = layers.Input(shape=(size, size, 3))
    x = augment(R)(inp)
    x = layers.Rescaling(1 / 255.0)(x)
    x = layers.Conv2D(32, 3, padding="same", activation="relu")(x)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dense(512, activation="relu")(x); x = layers.Dropout(R["dropout"])(x)
    x = layers.Dense(256, activation="relu")(x); x = layers.Dropout(R["dropout"])(x)
    out = layers.Dense(NUM_CLASSES, activation="softmax", dtype="float32")(x)
    return compile_model(Model(inp, out, name="DNN"), R, R["lr"]["DNN"])

builders = {"ResNet50": build_resnet, "InceptionV3": build_inception, "DNN": build_dnn}

def get_lr(model):
    opt = getattr(model.optimizer, "inner_optimizer", model.optimizer)
    return float(tf.keras.backend.get_value(opt.learning_rate))

def set_lr(model, value):
    opt = getattr(model.optimizer, "inner_optimizer", model.optimizer)
    opt.learning_rate.assign(value)

